-- 0. 修复表名不一致问题 (Fix table name mismatch from previous migration)
-- Check if ledger_reports exists and ledgers does not
DO $$
BEGIN
    IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'ledger_reports')
    AND NOT EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'ledgers') THEN
        ALTER TABLE ledger_reports RENAME TO ledgers;
    END IF;
END $$;

-- 如果 ledgers 表完全不存在（预防性创建），则创建它
CREATE TABLE IF NOT EXISTS ledgers (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  report_type text not null check (report_type in ('weekly', 'monthly')),
  period_start timestamptz not null,
  period_end timestamptz not null,
  item_count int default 0,
  content jsonb,
  created_at timestamptz default now()
);

-- Enable RLS for ledgers if newly created
ALTER TABLE ledgers ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_policies WHERE tablename = 'ledgers' AND policyname = 'Users can view their own ledger reports') THEN
        CREATE POLICY "Users can view their own ledger reports" ON ledgers FOR SELECT USING (auth.uid() = user_id);
    END IF;
    -- Add delete policy if missing
     IF NOT EXISTS (SELECT FROM pg_policies WHERE tablename = 'ledgers' AND policyname = 'Users can delete their own ledger reports') THEN
        CREATE POLICY "Users can delete their own ledger reports" ON ledgers FOR DELETE USING (auth.uid() = user_id);
    END IF;
END $$;

