-- 2. 创建 ledger_entries 表 (如果不存在)
CREATE TABLE IF NOT EXISTS ledger_entries (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    ledger_id BIGINT REFERENCES ledgers(id) ON DELETE CASCADE,
    entry_type TEXT DEFAULT 'financial' CHECK (entry_type IN ('financial', 'bookmark', 'rediscover')),
    title TEXT,
    platform TEXT,
    url TEXT,
    occurred_at TIMESTAMPTZ,
    bookmark_id UUID REFERENCES bookmarks(id) ON DELETE SET NULL,
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS for ledger_entries
ALTER TABLE ledger_entries ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_policies WHERE tablename = 'ledger_entries' AND policyname = 'Users can view their own ledger entries') THEN
        CREATE POLICY "Users can view their own ledger entries" ON ledger_entries FOR SELECT USING (
            EXISTS (SELECT 1 FROM ledgers WHERE ledgers.id = ledger_entries.ledger_id AND ledgers.user_id = auth.uid())
        );
    END IF;
END $$;


