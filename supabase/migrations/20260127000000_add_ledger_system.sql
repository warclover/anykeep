-- Create ledger_reports table for Weekly/Monthly bookmark reports
create table public.ledger_reports (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  report_type text not null check (report_type in ('weekly', 'monthly')),
  period_start timestamptz not null,
  period_end timestamptz not null,
  item_count int default 0,
  content jsonb, -- Stores the list items: [{time, platform, title, url}, ...]
  created_at timestamptz default now()
);

-- Add comment
comment on table public.ledger_reports is 'Stores weekly and monthly bookmark ledgers/reports';

-- Create index for faster querying by user and date
create index idx_ledger_reports_user_date on ledger_reports(user_id, created_at desc);
create index idx_ledger_reports_type_period on ledger_reports(user_id, report_type, period_start);

-- Enable RLS
alter table ledger_reports enable row level security;

-- RLS Policies
create policy "Users can view their own ledger reports"
  on ledger_reports for select
  using (auth.uid() = user_id);

create policy "Users can delete their own ledger reports"
  on ledger_reports for delete
  using (auth.uid() = user_id);

-- Only service role (cron jobs) should insert generally, but allowing user to insert via server functions is fine if needed.
-- For now, restricting insert/update might be too strict if we run it via RPC or server-side functions that inherit user context.
-- But typically reports are system generated. Let's allow insert for owner for testing/manual triggering purposes if they have the right permissions,
-- though usually this is run by service role.
-- Ideally:
create policy "Users can insert their own ledger reports"
  on ledger_reports for insert
  with check (auth.uid() = user_id);
