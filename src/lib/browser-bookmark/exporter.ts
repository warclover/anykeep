/**
 * 书签导出器
 * 将 AnyKeep 收藏导出为 Netscape Bookmark HTML 格式
 */

import type { Platform } from "@/types/supabase";

// ============================================
// 类型定义
// ============================================

/** 要导出的书签数据 */
export interface ExportBookmark {
  /** 书签标题 */
  title: string;
  /** 书签 URL */
  url: string;
  /** 添加时间 */
  addedAt?: string | Date;
  /** 描述 */
  description?: string;
  /** 文件夹路径 */
  folderPath?: string[];
  /** 来源平台 */
  platform?: Platform;
}

/** 导出配置 */
export interface ExportConfig {
  /** 导出文件名（不含扩展名） */
  filename?: string;
  /** 是否包含文件夹结构 */
  includeFolders?: boolean;
  /** 是否按平台分组 */
  groupByPlatform?: boolean;
  /** 根文件夹名称 */
  rootFolderName?: string;
}

/** 内部树结构 */
interface FolderNode {
  name: string;
  children: FolderNode[];
  bookmarks: ExportBookmark[];
}

// ============================================
// 常量
// ============================================

const DEFAULT_ROOT_NAME = "AnyKeep 导出";

const PLATFORM_NAMES: Partial<Record<Platform, string>> = {
  WECHAT_OFFICIAL_ACCOUNT: "微信公众号",
  BILIBILI: "B站",
  XIAOHONGSHU: "小红书",
  BROWSER_CHROME: "Chrome",
  BROWSER_EDGE: "Edge",
  BROWSER_FIREFOX: "Firefox",
  BROWSER_SAFARI: "Safari",
  UNKNOWN: "其他",
};

// ============================================
// HTML 生成
// ============================================

/**
 * 生成 Netscape Bookmark HTML 格式
 */
export function generateBookmarkHtml(
  bookmarks: ExportBookmark[],
  config: ExportConfig = {},
): string {
  const {
    includeFolders = true,
    groupByPlatform = false,
    rootFolderName = DEFAULT_ROOT_NAME,
  } = config;

  // 构建树结构
  const root: FolderNode = {
    name: rootFolderName,
    children: [],
    bookmarks: [],
  };

  if (groupByPlatform) {
    // 按平台分组
    const platformGroups = new Map<Platform, ExportBookmark[]>();

    for (const bookmark of bookmarks) {
      const platform = bookmark.platform || "UNKNOWN";
      const platformBookmarks = platformGroups.get(platform);
      if (platformBookmarks) {
        platformBookmarks.push(bookmark);
      } else {
        platformGroups.set(platform, [bookmark]);
      }
    }

    // 为每个平台创建文件夹
    for (const [platform, items] of platformGroups) {
      const folderName = PLATFORM_NAMES[platform] || platform;
      const folder: FolderNode = {
        name: folderName,
        children: [],
        bookmarks: [],
      };

      if (includeFolders) {
        // 在平台文件夹内保留原始文件夹结构
        buildFolderTree(items, folder);
      } else {
        folder.bookmarks = items;
      }

      root.children.push(folder);
    }
  } else if (includeFolders) {
    // 保留原始文件夹结构
    buildFolderTree(bookmarks, root);
  } else {
    // 扁平列表
    root.bookmarks = bookmarks;
  }

  // 生成 HTML
  const lines: string[] = [];

  // HTML 头部
  lines.push("<!DOCTYPE NETSCAPE-Bookmark-file-1>");
  lines.push("<!-- This is an automatically generated file.");
  lines.push(
    `     It was generated by AnyKeep on ${new Date().toISOString()} -->`,
  );
  lines.push(
    '<META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=UTF-8">',
  );
  lines.push("<TITLE>Bookmarks</TITLE>");
  lines.push("<H1>Bookmarks</H1>");
  lines.push("<DL><p>");

  // 生成根内容
  generateFolderContent(root, lines, 1);

  // 关闭标签
  lines.push("</DL><p>");

  return lines.join("\n");
}

/**
 * 构建文件夹树
 */
function buildFolderTree(bookmarks: ExportBookmark[], root: FolderNode): void {
  for (const bookmark of bookmarks) {
    const path = bookmark.folderPath || [];

    if (path.length === 0) {
      root.bookmarks.push(bookmark);
      continue;
    }

    // 沿路径创建/查找文件夹
    let current = root;
    for (const folderName of path) {
      let child = current.children.find((c) => c.name === folderName);
      if (!child) {
        child = {
          name: folderName,
          children: [],
          bookmarks: [],
        };
        current.children.push(child);
      }
      current = child;
    }

    current.bookmarks.push(bookmark);
  }
}

/**
 * 生成文件夹内容 HTML
 */
function generateFolderContent(
  folder: FolderNode,
  lines: string[],
  indent: number,
): void {
  const pad = "    ".repeat(indent);

  // 添加子文件夹
  for (const child of folder.children) {
    const addDate = Math.floor(Date.now() / 1000);
    lines.push(
      `${pad}<DT><H3 ADD_DATE="${addDate}">${escapeHtml(child.name)}</H3>`,
    );
    lines.push(`${pad}<DL><p>`);
    generateFolderContent(child, lines, indent + 1);
    lines.push(`${pad}</DL><p>`);
  }

  // 添加书签
  for (const bookmark of folder.bookmarks) {
    const addDate = getAddDateTimestamp(bookmark.addedAt);
    const attrs = [
      `HREF="${escapeHtml(bookmark.url)}"`,
      `ADD_DATE="${addDate}"`,
    ];

    lines.push(
      `${pad}<DT><A ${attrs.join(" ")}>${escapeHtml(bookmark.title)}</A>`,
    );

    // 添加描述（如果有）
    if (bookmark.description) {
      lines.push(`${pad}<DD>${escapeHtml(bookmark.description)}`);
    }
  }
}

/**
 * 获取添加时间戳（Unix 秒）
 */
function getAddDateTimestamp(addedAt?: string | Date): number {
  if (!addedAt) {
    return Math.floor(Date.now() / 1000);
  }

  const date = typeof addedAt === "string" ? new Date(addedAt) : addedAt;
  return Math.floor(date.getTime() / 1000);
}

/**
 * HTML 转义
 */
function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

// ============================================
// 工具函数
// ============================================

/**
 * 生成导出文件名
 */
export function generateExportFilename(
  platform?: Platform,
  date?: Date,
): string {
  const d = date || new Date();
  const dateStr = d.toISOString().slice(0, 10).replace(/-/g, "");

  if (platform) {
    const platformName = PLATFORM_NAMES[platform] || platform;
    return `anykeep_${platformName}_${dateStr}.html`;
  }

  return `anykeep_bookmarks_${dateStr}.html`;
}

/**
 * 创建下载 Blob
 */
export function createDownloadBlob(html: string): Blob {
  return new Blob([html], { type: "text/html;charset=utf-8" });
}

/**
 * 触发浏览器下载
 */
export function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * 导出并下载
 */
export function exportAndDownload(
  bookmarks: ExportBookmark[],
  config: ExportConfig = {},
): void {
  const html = generateBookmarkHtml(bookmarks, config);
  const blob = createDownloadBlob(html);
  const filename = config.filename
    ? `${config.filename}.html`
    : generateExportFilename();

  triggerDownload(blob, filename);
}
