/**
 * 负面约束定义
 *
 * 防止 LLM 生成低质量摘要的硬性规则
 *
 * @version 1.0.0
 * @since 2026-03-07
 */

/**
 * 完整版负面约束（用于标准/增强模式）
 */
export const NEGATIVE_CONSTRAINTS = `【禁止事项 — 违反任一条将导致输出无效】
1. 禁止编造原文中不存在的信息，所有要点必须有原文依据
2. 禁止使用模糊表述，如"一些"、"可能"、"据说"、"大概"、"等等"
3. 禁止将标题原封不动作为 tldr 内容
4. 禁止生成与内容无关的通用标签，如"收藏"、"阅读"、"分享"、"好文"
5. 禁止在 key_points 中使用序号词开头，如"首先"、"其次"、"最后"
6. 每个 key_point 必须包含具体信息或数据，不能是空泛概述
7. keywords 必须与内容强相关，至少包含 1 个领域标签和 1 个主题标签
8. tldr 不得超过 50 字，必须直接说明核心价值，不使用"本文介绍了"等套话`;

/**
 * 简化版负面约束（用于 MapReduce Map 阶段等场景）
 */
export const NEGATIVE_CONSTRAINTS_LITE = `【禁止事项】
1. 禁止编造原文中不存在的信息
2. 禁止使用模糊表述
3. 每个要点必须包含具体信息`;
